//! Compact-wire grammar: production-reader oracle plus generated GBNF.
//!
//! The GBNF is generated from the CoLisp and Co-Forth reader lexicons. It is
//! a complete-response recognizer, not a proof of types, vocabulary, stack
//! effects, capabilities, or host-effect safety. Provider-native tool calls
//! remain a separate channel.

use crate::gbnf;
use finch_coforth::{forth_lexicon, read_forth_source};
use finch_colisp::{lisp_lexicon, parse_str};
use finch_vm_core::ProgramLanguage;
use std::fmt::Write as _;
use std::sync::OnceLock;

/// Version of the published compact-wire GBNF.
pub const WIRE_GRAMMAR_VERSION: u32 = 1;

/// Path of the committed grammar artifact, relative to the repository root.
pub const WIRE_GRAMMAR_ARTIFACT: &str = "vocabulary/language/wire.gbnf";

#[cfg(test)]
const PUBLISHED_WIRE_GBNF: &str = include_str!("../../../vocabulary/language/wire.gbnf");

/// Why a compact-wire submission was rejected before compilation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WireReject {
    /// Stable diagnostic code such as `E-WIRE-002` or `E-READ-008`.
    pub code: String,
    /// Human-readable reason. Not a semantic safety proof.
    pub message: String,
}

impl std::fmt::Display for WireReject {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: {}", self.code, self.message)
    }
}

/// Production-reader oracle for a complete compact-wire `ProgramSubmission`.
///
/// Dispatch uses [`ProgramLanguage::infer_wire_source`]. Lisp uses the CoLisp
/// reader; Co-Forth uses the Co-Forth tokenizer plus syntactic completeness.
/// Unknown words are accepted.
pub fn accepts_wire_source(source: &str) -> Result<ProgramLanguage, WireReject> {
    let language = ProgramLanguage::infer_wire_source(source).map_err(dispatch_reject)?;
    match language {
        ProgramLanguage::Lisp => {
            parse_str(source).map_err(|error| WireReject {
                code: "E-READ-LISP".to_string(),
                message: error.to_string(),
            })?;
        }
        ProgramLanguage::Forth => {
            if let Err(errors) = read_forth_source("wire.forth", source) {
                let code = errors
                    .first()
                    .map(|error| error.code.clone())
                    .unwrap_or_else(|| "E-READ-FORTH".to_string());
                let message = errors
                    .iter()
                    .map(|error| error.message.as_str())
                    .collect::<Vec<_>>()
                    .join("; ");
                return Err(WireReject { code, message });
            }
        }
    }
    Ok(language)
}

/// True when the published GBNF accepts `source` as a complete submission.
pub fn accepts_published_grammar(source: &str) -> bool {
    gbnf::matches(published_grammar(), source)
}

/// Render the canonical compact-wire GBNF from production reader lexicons.
pub fn render_wire_gbnf() -> String {
    let lisp = lisp_lexicon();
    let forth = forth_lexicon();
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Finch compact-wire ProgramSubmission grammar v{WIRE_GRAMMAR_VERSION}"
    );
    let _ = writeln!(
        out,
        "# Generated from production Lisp/Co-Forth reader lexicons by finch_language::render_wire_gbnf."
    );
    let _ = writeln!(
        out,
        "# Complete-response recognizer only. Not a proof of types, capabilities, or host-effect safety."
    );
    let _ = writeln!(
        out,
        "# Markdown fences and empty submissions are rejected. Provider-native tool calls are a separate channel."
    );
    let _ = writeln!(
        out,
        "# Do not edit this file by hand. Update the generator and regenerate {WIRE_GRAMMAR_ARTIFACT}."
    );
    let _ = writeln!(out);

    rule(
        &mut out,
        "root",
        "lead ( lisp-program | forth-program ) lead",
    );
    rule(&mut out, "lead", "unicode-ws*");
    rule(&mut out, "unicode-ws", &unicode_whitespace_class());

    rule(
        &mut out,
        "lisp-program",
        "lisp-list lisp-gap* ( lisp-form lisp-gap* )*",
    );
    rule(
        &mut out,
        "lisp-gap",
        "unicode-ws | lisp-line-comment | lisp-block-comment",
    );
    rule(
        &mut out,
        "lisp-line-comment",
        &format!("{} [^\\n]*", gbnf_literal(&lisp.line_comment.to_string())),
    );
    rule(
        &mut out,
        "lisp-block-comment",
        &format!(
            "{} lisp-block-body {}",
            gbnf_literal(lisp.block_comment_open),
            gbnf_literal(lisp.block_comment_close)
        ),
    );
    rule(&mut out, "lisp-block-body", "( [^|] | \"|\" [^#] )*");
    rule(
        &mut out,
        "lisp-form",
        "lisp-splice | lisp-unquote | lisp-quote | lisp-quasiquote | lisp-list | lisp-string | lisp-math | lisp-brace | lisp-array | lisp-atom",
    );
    rule(
        &mut out,
        "lisp-splice",
        &format!("{} lisp-gap* lisp-form", gbnf_literal(lisp.unquote_splice)),
    );
    rule(
        &mut out,
        "lisp-unquote",
        &format!(
            "{} lisp-gap* lisp-form",
            gbnf_literal(&lisp.unquote.to_string())
        ),
    );
    rule(
        &mut out,
        "lisp-quote",
        &format!(
            "{} lisp-gap* lisp-form",
            gbnf_literal(&lisp.quote.to_string())
        ),
    );
    rule(
        &mut out,
        "lisp-quasiquote",
        &format!(
            "{} lisp-gap* lisp-form",
            gbnf_literal(&lisp.quasiquote.to_string())
        ),
    );
    rule(
        &mut out,
        "lisp-list",
        &format!(
            "{} lisp-gap* ( lisp-form lisp-gap* )* {}",
            gbnf_literal(&lisp.list_open.to_string()),
            gbnf_literal(&lisp.list_close.to_string())
        ),
    );
    rule(
        &mut out,
        "lisp-string",
        &format!(
            "{} lisp-str-char* {}",
            gbnf_literal(&lisp.string_delimiter.to_string()),
            gbnf_literal(&lisp.string_delimiter.to_string())
        ),
    );
    rule(&mut out, "lisp-str-char", r#" "\\" . | [^"\\] "#);
    rule(
        &mut out,
        "lisp-math",
        &format!(
            "{} [^{}]* {}",
            gbnf_literal(&lisp.math_delimiter.to_string()),
            class_escape(lisp.math_delimiter),
            gbnf_literal(&lisp.math_delimiter.to_string())
        ),
    );
    rule(&mut out, "lisp-brace", "json-object | lisp-record");
    rule(
        &mut out,
        "lisp-record",
        &format!(
            "{} lisp-gap* ( \":\" lisp-atom lisp-gap+ lisp-form lisp-gap* )* {}",
            gbnf_literal(&lisp.record_open.to_string()),
            gbnf_literal(&lisp.record_close.to_string())
        ),
    );
    rule(&mut out, "lisp-array", "json-array");
    rule(&mut out, "lisp-atom", "lisp-atom-piece+");
    rule(&mut out, "lisp-atom-piece", "lisp-plain | lisp-angles");
    rule(&mut out, "lisp-plain", &lisp_plain_class());
    rule(&mut out, "lisp-angles", "\"<\" lisp-angle-body \">\"");
    rule(
        &mut out,
        "lisp-angle-body",
        "( lisp-plain | \",\" | lisp-angles )*",
    );

    rule(&mut out, "json-ws", "unicode-ws");
    rule(&mut out, "json-object", "\"{\" json-ws* json-object-body");
    rule(
        &mut out,
        "json-object-body",
        "\"}\" | json-member ( json-ws* \",\" json-ws* json-member )* json-ws* \"}\"",
    );
    rule(
        &mut out,
        "json-member",
        "json-string json-ws* \":\" json-ws* json-value",
    );
    rule(&mut out, "json-array", "\"[\" json-ws* json-array-body");
    rule(
        &mut out,
        "json-array-body",
        "\"]\" | json-value ( json-ws* \",\" json-ws* json-value )* json-ws* \"]\"",
    );
    rule(
        &mut out,
        "json-value",
        "json-object | json-array | json-string | json-number | \"true\" | \"false\" | \"null\"",
    );
    rule(&mut out, "json-string", r#" "\"" json-str-char* "\"" "#);
    rule(&mut out, "json-str-char", r#" "\\" . | [^"\\] "#);
    rule(&mut out, "json-number", r#" "-"? [0-9]+ ( "." [0-9]+ )? "#);

    rule(&mut out, "ascii-ws", r#"[ \t\n\r\x0b\x0c]"#);
    rule(&mut out, "forth-ws", "ascii-ws");
    rule(
        &mut out,
        "forth-comment",
        &format!("{} [^\\n]*", gbnf_literal(&forth.line_comment.to_string())),
    );
    rule(
        &mut out,
        "forth-gap",
        &format!(
            "forth-ws | {} | forth-comment",
            gbnf_literal(&forth.comma_separator.to_string())
        ),
    );
    rule(&mut out, "forth-program", "forth-ws* forth-nonempty");
    rule(
        &mut out,
        "forth-nonempty",
        "forth-comment forth-more | forth-first forth-more",
    );
    rule(
        &mut out,
        "forth-more",
        "forth-gap* ( forth-item forth-gap* )*",
    );
    rule(
        &mut out,
        "forth-first",
        "forth-raw | forth-string | forth-def | forth-compact | forth-collection | forth-type | forth-bracket | forth-json | forth-record | forth-first-word",
    );
    rule(
        &mut out,
        "forth-item",
        "forth-raw | forth-string | forth-def | forth-compact | forth-collection | forth-type | forth-bracket | forth-json | forth-record | forth-word",
    );

    let raw_openers: Vec<_> = forth
        .string_openers
        .iter()
        .filter(|opener| opener.raw)
        .map(|opener| {
            format!(
                "{} raw-body {}",
                gbnf_literal(opener.spelling),
                gbnf_literal(forth.raw_string_close)
            )
        })
        .collect();
    rule(&mut out, "forth-raw", &raw_openers.join(" | "));
    rule(
        &mut out,
        "raw-body",
        r#"( [^"] | "\"" [^"] | "\"\"" [^"] )*"#,
    );

    let escaped: Vec<_> = forth
        .string_openers
        .iter()
        .filter(|opener| !opener.raw)
        .map(|opener| {
            if opener.skip_one_ascii_ws {
                format!("{} ascii-ws? esc-body", gbnf_literal(opener.spelling))
            } else {
                format!("{} esc-body", gbnf_literal(opener.spelling))
            }
        })
        .collect();
    rule(&mut out, "forth-string", &escaped.join(" | "));
    rule(&mut out, "esc-body", r#" esc-char* "\"" "#);
    rule(&mut out, "esc-char", r#" "\\" . | [^"\\] "#);

    rule(
        &mut out,
        "forth-def",
        &format!(
            "{} forth-gap+ forth-word forth-gap+ {} forth-sig-body {} forth-def-body {}",
            gbnf_literal(forth.definition_start),
            gbnf_literal(forth.signature_open),
            gbnf_literal(forth.signature_close),
            gbnf_literal(forth.definition_end)
        ),
    );
    rule(
        &mut out,
        "forth-sig-body",
        "( forth-gap | forth-string | forth-raw | forth-sig-word | forth-compact | forth-type )*",
    );
    rule(&mut out, "forth-sig-word", &forth_sig_word_class());
    rule(
        &mut out,
        "forth-def-body",
        "( forth-gap+ forth-body-item )* forth-gap*",
    );
    rule(
        &mut out,
        "forth-body-item",
        "forth-raw | forth-string | forth-compact | forth-collection | forth-type | forth-bracket | forth-json | forth-record | forth-body-word",
    );

    let compact_alts: Vec<_> = forth
        .compact_type_prefixes
        .iter()
        .map(|prefix| format!("{} [^\\n\\r\\t \"}}]+ \"}}\"", gbnf_literal(prefix)))
        .collect();
    rule(&mut out, "forth-compact", &compact_alts.join(" | "));

    let collection_alts: Vec<_> = forth
        .collection_openers
        .iter()
        .chain(forth.collection_closers.iter())
        .map(|spelling| gbnf_literal(spelling))
        .collect();
    rule(&mut out, "forth-collection", &collection_alts.join(" | "));

    let type_alts: Vec<_> = forth
        .parameterized_type_prefixes
        .iter()
        .map(|prefix| format!("{} [^ \\t\\n\\r>]* \">\"", gbnf_literal(prefix)))
        .collect();
    rule(&mut out, "forth-type", &type_alts.join(" | "));

    rule(&mut out, "forth-bracket", "forth-quote | forth-list");
    rule(
        &mut out,
        "forth-quote",
        &format!(
            "{} forth-gap* {} forth-gap* forth-qhead {} forth-quote-body {}",
            gbnf_literal(&forth.list_open.to_string()),
            gbnf_literal(forth.quotation_arrow),
            gbnf_literal(forth.quotation_pipe),
            gbnf_literal(&forth.list_close.to_string())
        ),
    );
    rule(&mut out, "forth-qhead", "( forth-word forth-gap* )*");
    rule(
        &mut out,
        "forth-quote-body",
        "( forth-gap | forth-body-item )*",
    );
    rule(
        &mut out,
        "forth-list",
        &format!(
            "{} forth-gap* ( forth-body-item forth-gap* )* {}",
            gbnf_literal(&forth.list_open.to_string()),
            gbnf_literal(&forth.list_close.to_string())
        ),
    );
    rule(&mut out, "forth-json", "json-object");
    rule(
        &mut out,
        "forth-record",
        &format!(
            "{} forth-gap* ( forth-word forth-gap+ forth-body-item forth-gap* )* {}",
            gbnf_literal(&forth.record_open.to_string()),
            gbnf_literal(&forth.record_close.to_string())
        ),
    );
    rule(
        &mut out,
        "forth-word",
        "\":\" forth-word-char+ | forth-plain-start forth-word-char*",
    );
    rule(
        &mut out,
        "forth-body-word",
        "\":\" forth-body-word-char+ | forth-body-plain-start forth-body-word-char*",
    );
    rule(
        &mut out,
        "forth-first-word",
        "\":\" forth-word-char+ | forth-first-start forth-word-char*",
    );
    rule(&mut out, "forth-plain-start", &forth_plain_start_class());
    rule(
        &mut out,
        "forth-body-plain-start",
        &forth_body_plain_start_class(),
    );
    rule(&mut out, "forth-word-char", &forth_word_class());
    rule(&mut out, "forth-body-word-char", &forth_body_word_class());
    rule(
        &mut out,
        "forth-first-start",
        &format!(
            "{} | \"`\" \"`\"? {}",
            forth_first_start_class(),
            forth_first_start_class()
        ),
    );

    out
}

fn published_grammar() -> &'static gbnf::Grammar {
    static GRAMMAR: OnceLock<gbnf::Grammar> = OnceLock::new();
    GRAMMAR.get_or_init(|| {
        gbnf::parse(&render_wire_gbnf()).expect("generated Finch wire GBNF must parse")
    })
}

fn dispatch_reject(error: impl std::fmt::Display) -> WireReject {
    let message = error.to_string();
    let code = message
        .split_once(':')
        .map(|(code, _)| code.trim().to_string())
        .unwrap_or_else(|| "E-WIRE".to_string());
    WireReject { code, message }
}

fn rule(out: &mut String, name: &str, body: &str) {
    let _ = writeln!(out, "{name} ::= {body}");
}

fn gbnf_literal(text: &str) -> String {
    let mut out = String::from("\"");
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn class_escape(ch: char) -> String {
    match ch {
        '\\' | ']' | '-' | '^' => format!("\\{ch}"),
        '\n' => "\\n".to_string(),
        '\r' => "\\r".to_string(),
        '\t' => "\\t".to_string(),
        c => c.to_string(),
    }
}

fn push_class_char(out: &mut String, ch: char) {
    match ch {
        '\\' | ']' | '-' | '^' => {
            out.push('\\');
            out.push(ch);
        }
        '\n' => out.push_str("\\n"),
        '\r' => out.push_str("\\r"),
        '\t' => out.push_str("\\t"),
        c if (c as u32) < 0x20 || c == '\u{7f}' => {
            let _ = write!(out, "\\x{:02x}", c as u32);
        }
        c => out.push(c),
    }
}

fn unicode_whitespace_class() -> String {
    let mut out = String::from("[");
    for ch in (0..=0x10FFFF)
        .filter_map(char::from_u32)
        .filter(|ch| ch.is_whitespace())
    {
        push_class_char(&mut out, ch);
    }
    out.push(']');
    out
}

fn lisp_plain_class() -> String {
    // Complement of whitespace and the reader atom delimiters plus type-arg brackets.
    let mut forbidden = String::from("[^");
    for ch in (0..=0x10FFFF)
        .filter_map(char::from_u32)
        .filter(|ch| ch.is_whitespace())
    {
        push_class_char(&mut forbidden, ch);
    }
    for ch in "(){}\"';`,<>".chars() {
        push_class_char(&mut forbidden, ch);
    }
    forbidden.push(']');
    forbidden
}

fn forth_word_class() -> String {
    negated_class(&[
        b'\t', b'\n', 0x0b, 0x0c, b'\r', b' ', b',', b'"', b'[', b']', b'}',
    ])
}

fn forth_body_word_class() -> String {
    negated_class(&[
        b'\t', b'\n', 0x0b, 0x0c, b'\r', b' ', b',', b'"', b'[', b']', b'}', b';',
    ])
}

fn forth_sig_word_class() -> String {
    negated_class(&[
        b'\t', b'\n', 0x0b, 0x0c, b'\r', b' ', b',', b'"', b'(', b')', b'[', b']', b'}',
    ])
}

fn forth_plain_start_class() -> String {
    negated_class(&[
        b':', b'\t', b'\n', 0x0b, 0x0c, b'\r', b' ', b',', b'"', b'[', b']', b'}',
    ])
}

fn forth_body_plain_start_class() -> String {
    negated_class(&[
        b':', b'\t', b'\n', 0x0b, 0x0c, b'\r', b' ', b',', b'"', b'[', b']', b'}', b';',
    ])
}

fn forth_first_start_class() -> String {
    negated_class(&[
        b'`', b'(', b':', b'\t', b'\n', 0x0b, 0x0c, b'\r', b' ', b',', b'"', b'[', b']', b'}',
    ])
}

fn negated_class(bytes: &[u8]) -> String {
    let mut out = String::from("[^");
    for byte in bytes {
        push_class_char(&mut out, *byte as char);
    }
    out.push(']');
    out
}

